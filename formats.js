  const REAL_NICHES = ['vayb', 'net', 'ved', 'work'];

  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  // Ключ шаблона — имя файла. Из офлайн-пака приходит 'templates-pack/tpl_x.jpg',
  // из трофеев/сети — что угодно, поэтому берём хвост пути и отсекаем query.
  function keyOf(src) {
    if (!src || typeof src !== 'string') return null;
    if (src.startsWith('data:')) return null;
    const tail = src.split('/').pop().split('?')[0];
    return FORMATS[tail] ? tail : null;
  }

  function formatFor(src) {
    const key = keyOf(src);
    return key ? { key, ...FORMATS[key] } : null;
  }

  // Колода без повторов на каждую пару (формат, ниша) — как в банке подписей.
  const decks = {};

  function nichesFor(niche) {
    return niche === 'all' || !niche ? REAL_NICHES : [niche];
  }

  function variantsFor(formatKey, niche) {
    const fmt = FORMATS[formatKey];
    if (!fmt) return [];
    const g = GRAMMARS[fmt.grammar];
    if (!g) return [];
    return nichesFor(niche).flatMap(n => g.variants(n));
  }

  // Возвращает набор реплик длиной ровно slots.length либо null, если варианты кончились.
  function nextVariant(formatKey, niche) {
    const deckKey = formatKey + '|' + (niche || 'all');
    if (!decks[deckKey] || !decks[deckKey].length) {
      decks[deckKey] = shuffle(variantsFor(formatKey, niche));
    }
    return decks[deckKey].length ? decks[deckKey].pop() : null;
  }

  function countFor(formatKey, niche) {
    return variantsFor(formatKey, niche).length;
  }

  // Список форматов для UI: ключ, заголовок, подсказка, сколько заготовок в нише.
