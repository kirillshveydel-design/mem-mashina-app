// Черновики мема про инфоповод («⚡ Сегодня» и режим «Событие»). Чистый модуль без DOM —
// поэтому его можно проверять в tests/run.js.
//
// Форма всегда одна: верх — что случилось, низ — моя реакция. Такая пара встаёт только на
// «реакционную» картинку (Эскобар, скелет, девочка и пожар), а не в Дрейка или trade offer,
// у которых другая грамматика. Раньше здесь были два низа-заглушки («Я узнал об этом из этого
// же поста», «Жду, когда это станет мемом») — на картинке они читаются как бессмыслица,
// и «Я: <фраза из чужой ниши>», где к релизу приклеивалась таможня. Всё это убрано.
window.__memEvents = (() => {
  'use strict';

  // Мелкие бытовые дела от первого лица, настоящее время — встают после «а я тут» / «я в это время».
  const TAILS = [
    'ТРЕТИЙ ЧАС ВЫБИРАЮ ШРИФТ ДЛЯ ПОСТА',
    'ПЕРЕКЛАДЫВАЮ ЗАДАЧИ ИЗ СПИСКА В СПИСОК',
    'ЧИНЮ ТО, ЧТО САМ ЖЕ И СЛОМАЛ',
    'ПЯТЫЙ РАЗ ПЕРЕЧИТЫВАЮ ОДНО ПИСЬМО',
    'ЖДУ, КОГДА ЗАГРУЗИТСЯ ПРЕВЬЮ',
    'ОБЪЯСНЯЮ МАМЕ, ЧЕМ Я ЗАНИМАЮСЬ',
    'ИЩУ, КУДА ДЕЛСЯ МОЙ ПОНЕДЕЛЬНИК',
    'СМОТРЮ НА ЭТО И МОЛЧУ'
  ];

  // Реакция на новость — годится к любой нише, поэтому не нужно угадывать, о чём событие.
  const REACTIONS = [
    'КИВАЮ С УМНЫМ ВИДОМ',
    'ДЕЛАЮ ВИД, ЧТО ПРЕДВИДЕЛ ЭТО ЕЩЁ В МАРТЕ',
    'СОХРАНИЛ В ЗАКЛАДКИ, ЧТОБЫ НИКОГДА НЕ ОТКРЫТЬ',
    'УЖЕ ПИШУ ПОСТ «ЧТО ЭТО ЗНАЧИТ ДЛЯ БИЗНЕСА»',
    'ПОШЁЛ ЗА ЧАЕМ. ВЕРНУСЬ, КОГДА ВСЁ ОБЪЯСНЯТ'
  ];

  const COMMENTS = [
    '«НУ ВСЁ, ЭТО КОНЕЦ»',
    '«А Я ГОВОРИЛ»',
    '«ЭТО ВСЁ ИИ»',
    '«А МОЖНО БЕЗ ЭТОГО?»'
  ];

  const SHAPES = [
    { top: e => e, bottom: v => 'А Я ТУТ ' + v.tail() },
    { top: e => 'ВСЕ ОБСУЖДАЮТ: ' + e, bottom: v => 'Я В ЭТО ВРЕМЯ ' + v.tail() },
    { top: e => e, bottom: v => 'МОЯ РЕАКЦИЯ: ' + v.reaction() },
    { top: e => 'НОВОСТЬ: ' + e, bottom: v => 'КОММЕНТАРИИ: ' + v.comment() }
  ];

  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  // Колода без возврата: два черновика в одной выдаче не получат одинаковый хвост.
  function drawFrom(pool) {
    let deck = shuffle(pool);
    return () => {
      if (!deck.length) deck = shuffle(pool);
      return deck.pop();
    };
  }

  // Три черновика разной формы про одно событие.
  function buildEventDrafts(rawEvent) {
    const event = String(rawEvent || '').trim().replace(/\s+/g, ' ').toUpperCase();
    if (!event) return [];
    const v = { tail: drawFrom(TAILS), reaction: drawFrom(REACTIONS), comment: drawFrom(COMMENTS) };
    return shuffle(SHAPES).slice(0, 3).map(shape => ({ top: shape.top(event), bottom: shape.bottom(v) }));
  }

  return { buildEventDrafts };
})();
